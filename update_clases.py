# Normalize for matching (handle unicode variants in Chat column)
def norm(s):
    return unicodedata.normalize('NFC', str(s))

ce_norm = {norm(x) for x in confirmacion_estado}
fd_norm = {norm(x) for x in facturacion_docs}
co_norm = {norm(x) for x in cotizacion}

# Step 1: Rename old class names
df['Clase'] = df['Clase'].replace({'Facturacion': 'Facturación_Documentos', 'Cotizacion': 'Cotización/Presupuesto'})

# Step 2: Apply in order (later wins for overlaps)
counts = {'Confirmación_Estado': 0, 'Facturación_Documentos': 0, 'Cotización/Presupuesto': 0}
for idx, row in df.iterrows():
    key = norm(row['Chat'])
    if key in ce_norm:
        df.at[idx, 'Clase'] = 'Confirmación_Estado'
        counts['Confirmación_Estado'] += 1
for idx, row in df.iterrows():
    key = norm(row['Chat'])
    if key in fd_norm:
        df.at[idx, 'Clase'] = 'Facturación_Documentos'
        counts['Facturación_Documentos'] += 1
for idx, row in df.iterrows():
    key = norm(row['Chat'])
    if key in co_norm:
        df.at[idx, 'Clase'] = 'Cotización/Presupuesto'
        counts['Cotización/Presupuesto'] += 1

df.to_csv('ML/tf_idf_matrix_clases.csv', index=False, encoding='utf-8-sig')

print('Applied new labels:')
